 *
 * Running it again rebuilds the test site: its database and its wp-content folder are replaced.
 * It refuses to work on a folder or database whose name does not contain "test".
 *
 * The site behaves like a customer's site: the plugin is a copy of this repository, the site talks to
 * the language server named in wptai-scenario.json (see ctl.php), and WP-Cron is off, so the
 * first-page-view installer is what runs.
 *
 * Environment overrides: WPTAI_SITE_DIR, WPTAI_SITE_URL, WPTAI_DB_NAME, WPTAI_DB_USER,
 * WPTAI_DB_PASSWORD, WPTAI_DB_HOST, WPTAI_CORE_SOURCE.
 *
 * Run: C:\xampp\php\php.exe tests/e2e-language-packs/setup.php
 */

$wptai = array(
	'site_dir'    => rtrim( strtr( getenv( 'WPTAI_SITE_DIR' ) ? getenv( 'WPTAI_SITE_DIR' ) : 'C:/xampp/htdocs/wp-test-ai', chr( 92 ), '/' ), '/' ),
	'site_url'    => rtrim( getenv( 'WPTAI_SITE_URL' ) ? getenv( 'WPTAI_SITE_URL' ) : 'http://localhost/wp-test-ai', '/' ),
	'db_name'     => getenv( 'WPTAI_DB_NAME' ) ? getenv( 'WPTAI_DB_NAME' ) : 'wp_test_ai',
	'db_user'     => getenv( 'WPTAI_DB_USER' ) ? getenv( 'WPTAI_DB_USER' ) : 'root',
	'db_password' => getenv( 'WPTAI_DB_PASSWORD' ) ? getenv( 'WPTAI_DB_PASSWORD' ) : '',
	'db_host'     => getenv( 'WPTAI_DB_HOST' ) ? getenv( 'WPTAI_DB_HOST' ) : 'localhost',
	'core_source' => rtrim( strtr( getenv( 'WPTAI_CORE_SOURCE' ) ? getenv( 'WPTAI_CORE_SOURCE' ) : 'C:/xampp/htdocs/wp', chr( 92 ), '/' ), '/' ),
	'plugin_dir'  => rtrim( strtr( dirname( __DIR__, 2 ), chr( 92 ), '/' ), '/' ),
	'theme'       => 'twentytwentyone',
	'admin_user'  => 'admin',
	'admin_pass'  => 'admin',
