if ( false === strpos( basename( $wptai['site_dir'] ), 'test' ) || false === strpos( $wptai['db_name'], 'test' ) ) {
	fwrite( STDERR, "Refusing to build a test site outside a folder and database with 'test' in the name.\n" );
	exit( 1 );
}

$step = isset( $argv[1] ) ? $argv[1] : 'all';

function wptai_copy_tree( $source, $target, $skip = array() ) {
	$source = rtrim( strtr( $source, chr( 92 ), '/' ), '/' );
	$target = rtrim( strtr( $target, chr( 92 ), '/' ), '/' );
	$filter = new RecursiveCallbackFilterIterator(
		new RecursiveDirectoryIterator( $source, FilesystemIterator::SKIP_DOTS ),
		function ( $item ) use ( $source, $skip ) {
			$relative = ltrim( strtr( substr( $item->getPathname(), strlen( $source ) ), chr( 92 ), '/' ), '/' );
			foreach ( $skip as $pattern ) {
				if ( fnmatch( $pattern, $relative, FNM_PATHNAME ) ) {
					return false;
				}
			}
			return true;
		}
	);
	$copied = 0;
	foreach ( new RecursiveIteratorIterator( $filter, RecursiveIteratorIterator::SELF_FIRST ) as $item ) {
		$destination = $target . '/' . ltrim( strtr( substr( $item->getPathname(), strlen( $source ) ), chr( 92 ), '/' ), '/' );
		if ( $item->isDir() ) {
			if ( ! is_dir( $destination ) ) {
				mkdir( $destination, 0777, true );
			}
			continue;
		}
		if ( ! is_dir( dirname( $destination ) ) ) {
			mkdir( dirname( $destination ), 0777, true );
		}
		copy( $item->getPathname(), $destination );
		$copied++;
	}
	return $copied;
}

/** Deletes a folder, but only somewhere below $root. */
function wptai_delete_tree( $dir, $root ) {
	$dir  = rtrim( strtr( $dir, chr( 92 ), '/' ), '/' );
	$root = rtrim( strtr( $root, chr( 92 ), '/' ), '/' );
	if ( ! is_dir( $dir ) ) {
		return;
	}
	if ( 0 !== strpos( strtolower( $dir ), strtolower( $root ) . '/' ) ) {
		throw new RuntimeException( "Refusing to delete {$dir}" );
	}
	$items = new RecursiveIteratorIterator(
		new RecursiveDirectoryIterator( $dir, FilesystemIterator::SKIP_DOTS ),
		RecursiveIteratorIterator::CHILD_FIRST
	);
	foreach ( $items as $item ) {
		$item->isDir() ? rmdir( $item->getPathname() ) : unlink( $item->getPathname() );
	}
	rmdir( $dir );
}

/** Plugin paths that never belong on the test site. */
function wptai_plugin_skip() {
	return array(
		'.git', '.github', '.vscode', '.claude', '.idea', 'node_modules', '_workspace', 'tests', 'docs',
		'temp/*', 'vendor/.git', 'vendor/*.zip', 'vendor/v4.1*', 'vendor/_logic',
	);
}

function wptai_wp_config( $c ) {
	$lines = array(
		'<?php',
		'// Language-pack e2e site. Generated by tests/e2e-language-packs/setup.php.',
		"define( 'DB_NAME', " . var_export( $c['db_name'], true ) . ' );',
		"define( 'DB_USER', " . var_export( $c['db_user'], true ) . ' );',
		"define( 'DB_PASSWORD', " . var_export( $c['db_password'], true ) . ' );',
		"define( 'DB_HOST', " . var_export( $c['db_host'], true ) . ' );',
		"define( 'DB_CHARSET', 'utf8mb4' );",
		"define( 'DB_COLLATE', '' );",
	);
	foreach ( array( 'AUTH_KEY', 'SECURE_AUTH_KEY', 'LOGGED_IN_KEY', 'NONCE_KEY', 'AUTH_SALT', 'SECURE_AUTH_SALT', 'LOGGED_IN_SALT', 'NONCE_SALT' ) as $key ) {
		$lines[] = "define( '{$key}', '" . bin2hex( random_bytes( 32 ) ) . "' );";
	}
	return implode( "\n", array_merge( $lines, array(
		"\$table_prefix = 'wp_';",
		"define( 'WP_HOME', " . var_export( $c['site_url'], true ) . ' );',
		"define( 'WP_SITEURL', " . var_export( $c['site_url'], true ) . ' );',
		"define( 'WP_DEBUG', true );",
		"define( 'WP_DEBUG_LOG', true );",
		"define( 'WP_DEBUG_DISPLAY', false );",
		"define( 'WP_ENVIRONMENT_TYPE', 'local' );",
		"define( 'EFB_DEBUG', true );",
		'// No WP-Cron and no server cron job: the first page view has to do the work.',
		"define( 'DISABLE_WP_CRON', true );",
		'',
		'// The scenario under test (tests/e2e-language-packs/ctl.php writes this file): which language',
		'// server the plugin talks to, and which wp-config constants the site has.',
		"\$wptai_scenario = is_file( __DIR__ . '/wptai-scenario.json' ) ? json_decode( (string) file_get_contents( __DIR__ . '/wptai-scenario.json' ), true ) : array();",
		"\$wptai_scenario = is_array( \$wptai_scenario ) ? \$wptai_scenario : array();",
		"define( 'EMSFB_LANGUAGE_PACKS_SERVER_URL', isset( \$wptai_scenario['server'] ) ? \$wptai_scenario['server'] : 'http://127.0.0.1/ws' );",
		"foreach ( isset( \$wptai_scenario['constants'] ) && is_array( \$wptai_scenario['constants'] ) ? \$wptai_scenario['constants'] : array() as \$wptai_name => \$wptai_value ) {",
		"\tif ( ! defined( \$wptai_name ) ) {",
		"\t\tdefine( \$wptai_name, \$wptai_value );",
		"\t}",
		'}',
		"if ( ! defined( 'FS_METHOD' ) ) {",
		"\tdefine( 'FS_METHOD', 'direct' );",
		'}',
		'',
		"if ( ! defined( 'ABSPATH' ) ) {",
		"\tdefine( 'ABSPATH', __DIR__ . '/' );",
		'}',
		"require_once ABSPATH . 'wp-settings.php';",
		'',
	) ) );
}

function wptai_fake_request( $c ) {
	$_SERVER['HTTP_HOST']      = parse_url( $c['site_url'], PHP_URL_HOST );
	$_SERVER['SERVER_NAME']    = $_SERVER['HTTP_HOST'];
	$_SERVER['SERVER_PORT']    = 80;
	$_SERVER['REQUEST_METHOD'] = 'GET';
	$_SERVER['REQUEST_URI']    = rtrim( (string) parse_url( $c['site_url'], PHP_URL_PATH ), '/' ) . '/';
}

function wptai_run_step( $name ) {
	$output = array();
	exec( escapeshellarg( PHP_BINARY ) . ' ' . escapeshellarg( __FILE__ ) . ' ' . escapeshellarg( $name ) . ' 2>&1', $output, $code );
	echo "[{$name}] " . implode( "\n[{$name}] ", $output ) . "\n";
	if ( 0 !== $code ) {
		fwrite( STDERR, "Step {$name} failed with exit code {$code}.\n" );
		exit( $code );
	}
}

if ( 'all' === $step ) {
	if ( ! file_exists( $wptai['site_dir'] . '/wp-includes/version.php' ) ) {
		echo "Copying WordPress core from {$wptai['core_source']}\n";
		wptai_copy_tree( $wptai['core_source'], $wptai['site_dir'], array(
			'wp-content', 'wp-config.php', '*.log', 'db_check_efb.php', 'enable-logic-addon.php',
			'opcache-probe-efb-tmp.php', 'phpinfo_test.php', 'test_efb_clean.php',
		) );
		// The core copy brings the development site's .htaccess, whose rewrite base is /wp/: pretty permalinks
		// on this site would send every request there.
		$htaccess = $wptai['site_dir'] . '/.htaccess';
		if ( is_file( $htaccess ) ) {
			$base = '/' . trim( (string) parse_url( $wptai['site_url'], PHP_URL_PATH ), '/' ) . '/';
			file_put_contents( $htaccess, str_replace( array( 'RewriteBase /wp/', ' /wp/index.php' ), array( 'RewriteBase ' . $base, ' ' . $base . 'index.php' ), (string) file_get_contents( $htaccess ) ) );
		}
	}

	$db   = new mysqli( $wptai['db_host'], $wptai['db_user'], $wptai['db_password'] );
	$name = $db->real_escape_string( $wptai['db_name'] );
	$db->query( "DROP DATABASE IF EXISTS `{$name}`" );
	$db->query( "CREATE DATABASE `{$name}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci" );
	echo "Database {$wptai['db_name']} created\n";

	$content = $wptai['site_dir'] . '/wp-content';
	wptai_delete_tree( $content, $wptai['site_dir'] );
	foreach ( array( 'themes', 'plugins', 'mu-plugins', 'uploads' ) as $folder ) {
		mkdir( $content . '/' . $folder, 0777, true );
	}
	wptai_copy_tree( $wptai['core_source'] . '/wp-content/themes/' . $wptai['theme'], $content . '/themes/' . $wptai['theme'] );
	$plugin_files = wptai_copy_tree( $wptai['plugin_dir'], $content . '/plugins/easy-form-builder', wptai_plugin_skip() );
	foreach ( glob( __DIR__ . '/mu-plugins/*.php' ) as $mu_plugin ) {
		copy( $mu_plugin, $content . '/mu-plugins/' . basename( $mu_plugin ) );
	}
	@unlink( $wptai['site_dir'] . '/wptai-scenario.json' );
	file_put_contents( $wptai['site_dir'] . '/wp-config.php', wptai_wp_config( $wptai ) );
	echo "wp-content rebuilt ({$plugin_files} plugin files)\n";

	wptai_run_step( 'install' );
	wptai_run_step( 'activate' );
	wptai_run_step( 'content' );
	exit( 0 );
}

if ( 'sync' === $step ) {
	// Refreshes the test site's copy of the plugin code and mu-plugins, nothing else.
	$copied = wptai_copy_tree( $wptai['plugin_dir'], $wptai['site_dir'] . '/wp-content/plugins/easy-form-builder', wptai_plugin_skip() );
	foreach ( glob( __DIR__ . '/mu-plugins/*.php' ) as $mu_plugin ) {
		copy( $mu_plugin, $wptai['site_dir'] . '/wp-content/mu-plugins/' . basename( $mu_plugin ) );
	}
	echo json_encode( array( 'synced_files' => $copied ) ), "\n";
	exit( 0 );
}

wptai_fake_request( $wptai );

if ( 'install' === $step ) {
	define( 'WP_INSTALLING', true );
	require $wptai['site_dir'] . '/wp-load.php';
	require_once ABSPATH . 'wp-admin/includes/upgrade.php';
	$installed = wp_install( 'wp-test-ai', $wptai['admin_user'], 'owner@wp-test-ai.test', false, '', wp_slash( $wptai['admin_pass'] ) );
	update_option( 'permalink_structure', '' );
	switch_theme( $wptai['theme'] );
	echo json_encode( array( 'installed' => ! empty( $installed['user_id'] ) ) ), "\n";
	exit( empty( $installed['user_id'] ) ? 1 : 0 );
}

if ( 'activate' === $step ) {
	require $wptai['site_dir'] . '/wp-load.php';
	require_once ABSPATH . 'wp-admin/includes/plugin.php';
	wp_set_current_user( 1 );
	$activated = activate_plugin( 'easy-form-builder/emsfb.php' );
	echo json_encode( array( 'activated' => ! is_wp_error( $activated ), 'error' => is_wp_error( $activated ) ? $activated->get_error_message() : null ) ), "\n";
	exit( is_wp_error( $activated ) ? 1 : 0 );
}

if ( 'content' === $step ) {
	require $wptai['site_dir'] . '/wp-load.php';
	wp_set_current_user( 1 );
	global $wpdb;

	$settings = Emsfb::get_default_settings_efb();
	$settings->emailSupporter = 'owner@wp-test-ai.test';
	$settings->smtp           = true;
	$settings->efb_version    = EMSFB_PLUGIN_VERSION;
	efbFunction::set_setting_Emsfb( $settings, 'owner@wp-test-ai.test' );
	delete_transient( 'emsfb_settings_transient' );
	get_setting_Emsfb( '_clear_cache' );

	// The first-run wizard and the plan chooser would cover the admin pages the scenarios open.
	emsfb_complete_onboarding_efb();
	update_option( 'emsfb_pro', 3 );
	update_option( 'emsfb_version', EMSFB_PLUGIN_VERSION );
	emsfb_check_file_access_efb();

	$fixture = json_decode( file_get_contents( __DIR__ . '/fixtures/plain.json' ), true );
	$wpdb->insert( $wpdb->prefix . 'emsfb_form', array(
		'form_name'       => 'Contact form',
		'form_structer'   => $fixture['structure'],
		'form_email'      => '',
		'form_type'       => $fixture['type'],
		'form_created_by' => (string) $fixture['created_by'],
		'form_access_by'  => (string) $fixture['access_by'],
		'status'          => 1,
	) );
	if ( ! $wpdb->insert_id ) {
		echo json_encode( array( 'error' => 'form insert failed: ' . $wpdb->last_error ) ), "\n";
		exit( 1 );
	}
	$form_id = (int) $wpdb->insert_id;
	$page_id = wp_insert_post( array(
		'post_type'    => 'page',
		'post_status'  => 'publish',
		'post_title'   => 'Contact us',
		'post_name'    => 'contact-us',
		'post_content' => '[EMS_Form_Builder id=' . $form_id . ']',
	) );
	update_option( 'wptai_form_page', array( 'form_id' => $form_id, 'page_id' => (int) $page_id, 'url' => get_permalink( $page_id ) ) );
	update_option( 'wptai_mail_log', array(), false );
	update_option( 'wptai_http_log', array(), false );

	echo json_encode( array(
		'form_id' => $form_id,
		'page_id' => (int) $page_id,
		'url'     => get_permalink( $page_id ),
		'login'   => array( 'user' => $wptai['admin_user'], 'password' => $wptai['admin_pass'] ),
	), JSON_UNESCAPED_SLASHES ), "\n";
	exit( 0 );
}

fwrite( STDERR, "Unknown step {$step}\n" );
exit( 1 );
