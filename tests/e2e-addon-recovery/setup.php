$step = isset( $argv[1] ) ? $argv[1] : 'all';

function efb_e2e_copy_tree( $source, $target, $skip = array() ) {
	$source = rtrim( str_replace( '\\', '/', $source ), '/' );
	$target = rtrim( str_replace( '\\', '/', $target ), '/' );
	$filter = new RecursiveCallbackFilterIterator(
		new RecursiveDirectoryIterator( $source, FilesystemIterator::SKIP_DOTS ),
		function ( $item ) use ( $source, $skip ) {
			$relative = ltrim( str_replace( '\\', '/', substr( $item->getPathname(), strlen( $source ) ) ), '/' );
			foreach ( $skip as $pattern ) {
				if ( fnmatch( $pattern, $relative, FNM_PATHNAME ) ) {
					return false;
				}
			}
			return true;
		}
	);
	$copied = 0;
	foreach ( new RecursiveIteratorIterator( $filter, RecursiveIteratorIterator::SELF_FIRST ) as $item ) {
		$destination = $target . '/' . ltrim( str_replace( '\\', '/', substr( $item->getPathname(), strlen( $source ) ) ), '/' );
		if ( $item->isDir() ) {
			if ( ! is_dir( $destination ) ) {
				mkdir( $destination, 0777, true );
			}
			continue;
		}
		if ( ! is_dir( dirname( $destination ) ) ) {
			mkdir( dirname( $destination ), 0777, true );
		}
		copy( $item->getPathname(), $destination );
		$copied++;
	}
	return $copied;
}

/** Deletes a folder, but only somewhere below $root. */
function efb_e2e_delete_tree( $dir, $root ) {
	$dir  = rtrim( str_replace( '\\', '/', $dir ), '/' );
	$root = rtrim( str_replace( '\\', '/', $root ), '/' );
	if ( ! is_dir( $dir ) ) {
		return;
	}
	if ( 0 !== strpos( strtolower( $dir ), strtolower( $root ) . '/' ) ) {
		throw new RuntimeException( "Refusing to delete {$dir}" );
	}
	$items = new RecursiveIteratorIterator(
		new RecursiveDirectoryIterator( $dir, FilesystemIterator::SKIP_DOTS ),
		RecursiveIteratorIterator::CHILD_FIRST
	);
	foreach ( $items as $item ) {
		$item->isDir() ? rmdir( $item->getPathname() ) : unlink( $item->getPathname() );
	}
	rmdir( $dir );
}

function efb_e2e_wp_config( $c ) {
	$lines = array(
		'<?php',
		'// Add-on recovery e2e site. Generated by tests/e2e-addon-recovery/setup.php.',
		"define( 'DB_NAME', " . var_export( $c['db_name'], true ) . ' );',
		"define( 'DB_USER', " . var_export( $c['db_user'], true ) . ' );',
		"define( 'DB_PASSWORD', " . var_export( $c['db_password'], true ) . ' );',
		"define( 'DB_HOST', " . var_export( $c['db_host'], true ) . ' );',
		"define( 'DB_CHARSET', 'utf8mb4' );",
		"define( 'DB_COLLATE', '' );",
	);
	foreach ( array( 'AUTH_KEY', 'SECURE_AUTH_KEY', 'LOGGED_IN_KEY', 'NONCE_KEY', 'AUTH_SALT', 'SECURE_AUTH_SALT', 'LOGGED_IN_SALT', 'NONCE_SALT' ) as $key ) {
		$lines[] = "define( '{$key}', '" . bin2hex( random_bytes( 32 ) ) . "' );";
	}
	return implode( "\n", array_merge( $lines, array(
		"\$table_prefix = 'wp_';",
		"define( 'WP_HOME', " . var_export( $c['site_url'], true ) . ' );',
		"define( 'WP_SITEURL', " . var_export( $c['site_url'], true ) . ' );',
		"define( 'WP_DEBUG', true );",
		"define( 'WP_DEBUG_LOG', true );",
		"define( 'WP_DEBUG_DISPLAY', false );",
		"define( 'FS_METHOD', 'direct' );",
		"define( 'WP_ENVIRONMENT_TYPE', 'local' );",
		'// ctl.php cron off: a site without WP-Cron and without a server cron job.',
		"if ( file_exists( __DIR__ . '/efb-e2e-no-cron.flag' ) && ! defined( 'DISABLE_WP_CRON' ) ) {",
		"\tdefine( 'DISABLE_WP_CRON', true );",
		'}',
		"if ( ! defined( 'ABSPATH' ) ) {",
		"\tdefine( 'ABSPATH', __DIR__ . '/' );",
		'}',
		"require_once ABSPATH . 'wp-settings.php';",
		'',
	) ) );
}

function efb_e2e_fake_request( $c ) {
	$_SERVER['HTTP_HOST']      = parse_url( $c['site_url'], PHP_URL_HOST );
	$_SERVER['SERVER_NAME']    = $_SERVER['HTTP_HOST'];
	$_SERVER['SERVER_PORT']    = 80;
	$_SERVER['REQUEST_METHOD'] = 'GET';
	$_SERVER['REQUEST_URI']    = rtrim( (string) parse_url( $c['site_url'], PHP_URL_PATH ), '/' ) . '/';
}

function efb_e2e_run_step( $name ) {
	$output = array();
	exec( escapeshellarg( PHP_BINARY ) . ' ' . escapeshellarg( __FILE__ ) . ' ' . escapeshellarg( $name ) . ' 2>&1', $output, $code );
	echo "[{$name}] " . implode( "\n[{$name}] ", $output ) . "\n";
	if ( 0 !== $code ) {
		fwrite( STDERR, "Step {$name} failed with exit code {$code}.\n" );
		exit( $code );
	}
}

if ( 'all' === $step ) {
	if ( ! file_exists( $efb_e2e['site_dir'] . '/wp-includes/version.php' ) ) {
		echo "Copying WordPress core from {$efb_e2e['core_source']}\n";
		efb_e2e_copy_tree( $efb_e2e['core_source'], $efb_e2e['site_dir'], array(
			'wp-content', 'wp-config.php', '*.log', 'db_check_efb.php', 'enable-logic-addon.php',
			'opcache-probe-efb-tmp.php', 'phpinfo_test.php', 'test_efb_clean.php',
		) );
	}

	$db = new mysqli( $efb_e2e['db_host'], $efb_e2e['db_user'], $efb_e2e['db_password'] );
	$name = $db->real_escape_string( $efb_e2e['db_name'] );
	$db->query( "DROP DATABASE IF EXISTS `{$name}`" );
	$db->query( "CREATE DATABASE `{$name}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci" );
	echo "Database {$efb_e2e['db_name']} created\n";

	$content = $efb_e2e['site_dir'] . '/wp-content';
	efb_e2e_delete_tree( $content, $efb_e2e['site_dir'] );
	foreach ( array( 'themes', 'plugins', 'mu-plugins', 'uploads', 'efb-e2e-zips' ) as $folder ) {
		mkdir( $content . '/' . $folder, 0777, true );
	}
	efb_e2e_copy_tree( $efb_e2e['core_source'] . '/wp-content/themes/' . $efb_e2e['theme'], $content . '/themes/' . $efb_e2e['theme'] );
	$plugin_files = efb_e2e_copy_tree( $efb_e2e['plugin_dir'], $content . '/plugins/easy-form-builder', efb_e2e_plugin_skip() );
	foreach ( glob( __DIR__ . '/mu-plugins/*.php' ) as $mu_plugin ) {
		copy( $mu_plugin, $content . '/mu-plugins/' . basename( $mu_plugin ) );
	}
	foreach ( glob( $efb_e2e['plugin_dir'] . '/vendor/*.zip' ) as $zip ) {
		copy( $zip, $content . '/efb-e2e-zips/' . basename( $zip ) );
	}
	@unlink( $efb_e2e['site_dir'] . '/efb-e2e-no-cron.flag' );
	file_put_contents( $efb_e2e['site_dir'] . '/wp-config.php', efb_e2e_wp_config( $efb_e2e ) );
	echo "wp-content rebuilt ({$plugin_files} plugin files)\n";

	efb_e2e_run_step( 'install' );
	efb_e2e_run_step( 'activate' );
	efb_e2e_run_step( 'content' );
	exit( 0 );
}

/** Plugin paths that never belong on the test site. */
function efb_e2e_plugin_skip( $extra = array() ) {
	return array_merge( array(
		'.git', '.github', '.vscode', '.claude', '.idea', 'node_modules', '_workspace', 'tests', 'docs',
		'temp/*', 'vendor/.git', 'vendor/*.zip', 'vendor/v4.1*', 'vendor/_logic',
	), $extra );
}

if ( 'sync' === $step ) {
	// Refreshes the test site's copy of the plugin code. Add-on folders are left
	// alone: scenarios remove them on purpose and ctl.php reset restores them.
	$addon_folders = array( 'human-shield', 'logic', 'stripe', 'paypal', 'persiadatepicker', 'arabicdatepicker', 'autofill', 'telegram', 'googlesheet', 'offline', 'persiapay' );
	$copied = efb_e2e_copy_tree(
		$efb_e2e['plugin_dir'],
		$efb_e2e['site_dir'] . '/wp-content/plugins/easy-form-builder',
		efb_e2e_plugin_skip( array_map( function ( $folder ) {
			return 'vendor/' . $folder;
		}, $addon_folders ) )
	);
	foreach ( glob( __DIR__ . '/mu-plugins/*.php' ) as $mu_plugin ) {
		copy( $mu_plugin, $efb_e2e['site_dir'] . '/wp-content/mu-plugins/' . basename( $mu_plugin ) );
	}
	echo json_encode( array( 'synced_files' => $copied ) ), "\n";
	exit( 0 );
}

efb_e2e_fake_request( $efb_e2e );

if ( 'install' === $step ) {
	define( 'WP_INSTALLING', true );
	require $efb_e2e['site_dir'] . '/wp-load.php';
	require_once ABSPATH . 'wp-admin/includes/upgrade.php';
	$installed = wp_install( 'EFB add-on recovery e2e', $efb_e2e['admin_user'], 'owner@e2e.test', false, '', wp_slash( $efb_e2e['admin_pass'] ) );
	update_option( 'permalink_structure', '' );
	switch_theme( $efb_e2e['theme'] );
	echo json_encode( array( 'installed' => ! empty( $installed['user_id'] ) ) ), "\n";
	exit( empty( $installed['user_id'] ) ? 1 : 0 );
}

if ( 'activate' === $step ) {
	require $efb_e2e['site_dir'] . '/wp-load.php';
	require_once ABSPATH . 'wp-admin/includes/plugin.php';
	wp_set_current_user( 1 );
	$activated = activate_plugin( 'easy-form-builder/emsfb.php' );
	echo json_encode( array( 'activated' => ! is_wp_error( $activated ), 'error' => is_wp_error( $activated ) ? $activated->get_error_message() : null ) ), "\n";
	exit( is_wp_error( $activated ) ? 1 : 0 );
}

if ( 'content' === $step ) {
	require $efb_e2e['site_dir'] . '/wp-load.php';
	wp_set_current_user( 1 );
	global $wpdb;

	// Form Security, Conditional Logic, Stripe and the Persian date picker are on.
	$baseline = array( 'AdnHSH' => 1, 'AdnSMF' => 1, 'AdnSPF' => 1, 'AdnPDP' => 1 );
	$settings = Emsfb::get_default_settings_efb();
	foreach ( $baseline as $addon_key => $value ) {
		$settings->{$addon_key} = (string) $value;
		update_option( 'emsfb_addon_' . $addon_key, $value );
	}
	$settings->emailSupporter = 'owner@e2e.test';
	$settings->smtp           = true;
	$settings->efb_version    = EMSFB_PLUGIN_VERSION;
	efbFunction::set_setting_Emsfb( $settings, 'owner@e2e.test' );
	delete_transient( 'emsfb_settings_transient' );
	get_setting_Emsfb( '_clear_cache' );

	update_option( 'efb_e2e_baseline_flags', $baseline );
	// The first-run wizard would cover the admin pages the scenarios click through.
	emsfb_complete_onboarding_efb();
	update_option( 'emsfb_pro', 3 );
	update_option( 'emsfb_version', EMSFB_PLUGIN_VERSION );
	update_option( 'efb_e2e_server_mode', 'ok' );
	$access = emsfb_check_file_access_efb();

	$forms = array();
	foreach ( array( 'plain', 'logic', 'stripe', 'pdate' ) as $slug ) {
		$fixture = json_decode( file_get_contents( __DIR__ . '/fixtures/' . $slug . '.json' ), true );
		$wpdb->insert( $wpdb->prefix . 'emsfb_form', array(
			'form_name'       => $fixture['name'],
			'form_structer'   => $fixture['structure'],
			'form_email'      => '',
			'form_type'       => $fixture['type'],
			'form_created_by' => (string) $fixture['created_by'],
			'form_access_by'  => (string) $fixture['access_by'],
			'status'          => 1,
		) );
		if ( ! $wpdb->insert_id ) {
			echo json_encode( array( 'error' => 'form insert failed: ' . $wpdb->last_error ) ), "\n";
			exit( 1 );
		}
		$forms[ $slug ] = (int) $wpdb->insert_id;
	}

	$layout = array(
		'plain'  => array( 'plain' ),
		'logic'  => array( 'logic' ),
		'stripe' => array( 'stripe' ),
		'pdate'  => array( 'pdate' ),
		'multi'  => array( 'plain', 'logic' ),
	);
	$pages = array();
	foreach ( $layout as $slug => $form_slugs ) {
		$ids = array_map( function ( $form_slug ) use ( $forms ) {
			return $forms[ $form_slug ];
		}, $form_slugs );
		$page_id = wp_insert_post( array(
			'post_type'    => 'page',
			'post_status'  => 'publish',
			'post_title'   => 'E2E ' . $slug,
			'post_name'    => 'e2e-' . $slug,
			'post_content' => implode( "\n\n", array_map( function ( $id ) {
				return '[EMS_Form_Builder id=' . $id . ']';
			}, $ids ) ),
		) );
		$pages[ $slug ] = array( 'page_id' => (int) $page_id, 'forms' => $ids, 'url' => get_permalink( $page_id ) );
	}
	update_option( 'efb_e2e_pages', $pages );
	update_option( 'efb_e2e_http_log', array(), false );
	update_option( 'efb_e2e_mail_log', array(), false );

	echo json_encode( array(
		'email_sending' => emsfb_is_email_sending_enabled_efb( get_setting_Emsfb( 'decoded' ) ),
		'file_access'   => ! empty( $access['status'] ),
		'forms'         => $forms,
		'pages'         => $pages,
		'login'         => array( 'user' => $efb_e2e['admin_user'], 'password' => $efb_e2e['admin_pass'] ),
	), JSON_UNESCAPED_SLASHES ), "\n";
	exit( 0 );
}

fwrite( STDERR, "Unknown step {$step}\n" );
exit( 1 );
